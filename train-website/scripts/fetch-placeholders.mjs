/**
 * Fetch every placeholder photograph once into public/placeholders.
 *
 * Why this exists
 * ---------------
 * D10 chose Picsum for deterministic grayscale placeholders, which was the
 * right instinct — but fetching them at *request* time means every photograph
 * on the site is one rate-limit away from a broken image. In review exactly
 * that happened: Picsum began timing out, Next's optimiser returned 504, and
 * images vanished on mobile while desktop still served an earlier cached
 * fetch, which read as a responsive bug rather than a network one.
 *
 * Downloading once removes the runtime dependency entirely and makes the
 * images load from the same origin, which is as fast as it gets.
 *
 * Source: the SAME Picsum URLs the site uses at runtime, so snapshotting
 * changes nothing about which photographs appear — only where they are served
 * from. An earlier revision pulled from a different host to work around
 * Picsum being unreachable; that silently swapped the pictures and was
 * reverted. If Picsum cannot be reached, this script fails rather than
 * substituting different images.
 *
 *   node scripts/fetch-placeholders.mjs
 *
 * Idempotent: files already on disk are skipped. Delete one to refresh it.
 * Until it is run, every seed is fetched from Picsum at request time.
 */
import { access, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { caseStudies } from "../src/data/case-studies.ts";
import { missionImage } from "../src/data/mission.ts";

const OUT = path.join(import.meta.dirname, "..", "public", "placeholders");
const MANIFEST = path.join(
  import.meta.dirname,
  "..",
  "src",
  "data",
  "local-placeholders.ts",
);

/** §13 — cap the long edge. next/image resizes anyway and smaller upstream
 *  requests are far likelier to succeed. Keeps files under the 150KB budget. */
const MAX_EDGE = 1200;

function scaled(width, height) {
  const factor = Math.min(1, MAX_EDGE / Math.max(width, height));
  return [Math.round(width * factor), Math.round(height * factor)];
}

const targets = [
  { seed: "train-hero", width: 1600, height: 1067 },
  {
    seed: missionImage.seed,
    width: missionImage.width,
    height: missionImage.height,
  },
  ...caseStudies.flatMap((c) => [c.heroImage, ...c.gallery]),
].map(({ seed, width, height }) => {
  const [w, h] = scaled(width, height);
  return { seed, w, h };
});

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

async function fetchOne({ seed, w, h }, attempt = 1) {
  const file = path.join(OUT, `${seed}.jpg`);
  if (await exists(file)) return { seed, status: "cached" };

  // Exactly the URL PlaceholderImage builds, so the photograph is identical.
  const url = `https://picsum.photos/seed/${seed}/${w}/${h}?grayscale`;

  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 1024) throw new Error("suspiciously small response");
    await writeFile(file, buf);
    return { seed, status: "ok", kb: Math.round(buf.length / 1024) };
  } catch (error) {
    if (attempt >= 4) return { seed, status: "failed", error: String(error) };
    await sleep(attempt * 3000);
    return fetchOne({ seed, w, h }, attempt + 1);
  }
}

await mkdir(OUT, { recursive: true });

const available = [];
let failed = 0;

for (const target of targets) {
  const result = await fetchOne(target);
  if (result.status === "failed") {
    failed++;
    console.log(`FAIL  ${result.seed}  ${result.error}`);
  } else {
    available.push(result.seed);
    console.log(
      `${result.status === "cached" ? "have" : "got "}  ${result.seed}` +
        (result.kb ? `  ${result.kb} KB` : ""),
    );
  }
  await sleep(600);
}

// The manifest lets PlaceholderImage choose the local file without a wasted
// 404 for seeds that were never downloaded.
const manifest = `/**
 * GENERATED by scripts/fetch-placeholders.mjs — do not edit by hand.
 *
 * Seeds with a downloaded photograph in public/placeholders. Anything not
 * listed falls back to fetching from Picsum at runtime.
 */
export const localPlaceholders = new Set<string>([
${available.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
]);
`;
await writeFile(MANIFEST, manifest);

console.log(`\n${available.length} available, ${failed} failed, ${targets.length} total`);
if (failed > 0) process.exitCode = 1;
